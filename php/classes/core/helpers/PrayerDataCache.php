<?php

namespace FivePrayer\Core\Helpers;

use FivePrayer\Core\Calendar\CalendarGenerator;
use FivePrayer\Core\Daily\NextPrayer;

defined('ABSPATH') || exit;

use FivePrayer\Core\Logging\Logger;

if (!class_exists('PrayerDataCache')) {

    /**
     * PrayerDataCache Class
     *
     * Handles caching of prayer timetable data and settings meta data
     * using WordPress transients, with an object cache group in front for
     * cross-request reuse. All object cache entries live in the
     * 'fiveprayer' group so they can be dropped together.
     *
     * Usage:
     * - PrayerDataCache::getMetaData() - For all settings meta.
     * - PrayerDataCache::getMetaValueByKey('some_key') - For specific meta key values (array of strings).
     * - PrayerDataCache::getSingleMetaValue('some_key') - For a single meta key value (string).
     * - PrayerDataCache::getTimetableData(month, year) - For timetable data.
     * - PrayerDataCache::getTimetableByDate('YYYY-MM-DD') - For specific date timetable.
     * - PrayerDataCache::invalidateAll() - To clear all related caches. IMPORTANT: Call this when data changes.
     */
    class PrayerDataCache
    {
        use \FivePrayer\Core\Helpers\Traits\MetaDataTrait;
        use \FivePrayer\Core\Helpers\Traits\TimetableDataTrait;
        use \FivePrayer\Core\Helpers\Traits\CacheInvalidationTrait;
        use \FivePrayer\Core\Helpers\Traits\CacheKeyTrait;

        /**
         * In-memory cache for all meta data for the current request.
         * @var array<object>|null
         */
        private static ?array $metaData = null;

        /**
         * In-memory cache for raw timetable data from DB, keyed by year and month.
         * @var array<string, array<object>>
         */
        private static array $timetableData = [];

        /**
         * In-memory cache for PROCESSED timetable data (from CalendarGenerator), keyed by locale.
         * @var array<string, array<object>>
         */
        private static array $processedTimetableCache = [];

        /**
         * Stores all transient keys generated by this class during the request.
         * Used by invalidateAll() to clear relevant transients.
         * @var array<string>
         */
        private static array $cacheKeys = [];

        /**
         * Batch of transients to be saved
         * @var array
         */
        private static array $transientBatch = [];

        /**
         * Base prefix for all transient keys generated by this class.
         */
        private const CACHE_KEY_PREFIX = 'fiveprayer_';

        /**
         * Default expiration time for transients (1 day).
         */
        private const DEFAULT_EXPIRATION = DAY_IN_SECONDS;

        /**
         * In-memory cache for next prayer data
         * @var array<object>|null
         */
        private static ?array $nextPrayerCache = null;

        /**
         * Timestamp for next prayer cache
         * @var int|null
         */
        private static ?int $nextPrayerCacheTime = null;

        /**
         * Timeout for next prayer cache in seconds
         */
        private const NEXT_PRAYER_CACHE_TIMEOUT = 60; // 1 minute timeout

        /**
         * Cache for today's prayer times to prevent multiple DB calls per request
         * @var object|null
         */
        private static ?object $todayPrayerTimesCache = null;

        /**
         * Date for the cached today's prayer times
         * @var string|null
         */
        private static ?string $todayPrayerTimesDate = null;
    }
}
